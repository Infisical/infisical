import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const USE_CASES_PATH = path.resolve(dir, "../../docs/snippets/app-connections/aws/use-cases.jsx");
const OUTPUT_PATH = path.resolve(dir, "../src/helpers/awsUseCasePolicies.ts");

export const loadUseCaseGroups = () => {
  const source = readFileSync(USE_CASES_PATH, "utf8").replace(
    "export const awsUseCaseGroups =",
    "return"
  );
  return new Function(source)();
};

export const buildPolicyStatements = () =>
  Object.fromEntries(
    loadUseCaseGroups()
      .flatMap((group) => group.options)
      .filter((option) => option.policy)
      .map((option) => [option.id, option.policy.statements])
  );

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const output = `// Generated by frontend/scripts/generate-aws-use-case-policies.mjs from
// docs/snippets/app-connections/aws/use-cases.jsx. Do not edit by hand.
type TStatement = {
  Sid: string;
  Effect: string;
  Action: string | string[];
  Resource: string | string[];
  Condition?: Record<string, unknown>;
};

export const AWS_USE_CASE_POLICY_STATEMENTS: Record<string, TStatement[]> = ${JSON.stringify(
    buildPolicyStatements(),
    null,
    2
  )};

export const getAwsPolicyJson = (useCaseIds: string[]) =>
  JSON.stringify(
    {
      Version: "2012-10-17",
      Statement: useCaseIds.flatMap((id) => AWS_USE_CASE_POLICY_STATEMENTS[id] ?? [])
    },
    null,
    2
  );
`;
  writeFileSync(OUTPUT_PATH, output);
}
