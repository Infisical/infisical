import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { v4LiveOrgPath, v4ThemeStorage } from "@infisical/cipher/lib/boot-theme-keys";
import { defaultV4Theme, v4Themes } from "@infisical/cipher/lib/theme-registry";
import { legacyV4Themes, v4ThemedValue } from "@infisical/cipher/lib/themes";
import tokens from "@infisical/cipher/tokens.json" with { type: "json" };

const indexPath = path.resolve(import.meta.dirname, "../index.html");
const check = process.argv.includes("--check");

const themed = new Map(
  Object.values(tokens as Record<string, unknown>)
    .flatMap((family) =>
      family && typeof family === "object" && "tokens" in family && Array.isArray(family.tokens)
        ? (family.tokens as { name: string; value: unknown }[])
        : []
    )
    .filter(
      (token): token is { name: string; value: Record<string, string> } =>
        typeof token.value === "object"
    )
    .map((token) => [token.name, token.value])
);
const themedValue = (theme: string, name: string): string | undefined => {
  const value = themed.get(name);
  if (!value) return undefined;
  const resolved = v4ThemedValue(v4Themes, theme, name, value);
  const alias = /^\{([^}]+)\}$/.exec(resolved)?.[1];
  return alias ? themedValue(theme, alias) : resolved;
};

const bootStart = "<!-- v4-boot: generated by v4:boot from @infisical/cipher/tokens.json -->";
const bootEnd = "<!-- /v4-boot -->";
const bootGrounds = v4Themes
  .map(
    (theme) =>
      `      html[data-v4-boot="${theme.id}"] { background: ${themedValue(theme.id, "inset")}; color-scheme: ${theme.scheme}; }`
  )
  .join("\n");
const bootScript = `(function () {
        var path = location.pathname;
        if (!/^\\/v4(?:\\/|$)/.test(path)) return;
        var schemes = ${JSON.stringify(Object.fromEntries(v4Themes.map((theme) => [theme.id, theme.scheme])))};
        var legacy = ${JSON.stringify(legacyV4Themes)};
        var defaults = ${JSON.stringify(defaultV4Theme)};
        var own = function (map, key) { return typeof key === "string" && Object.prototype.hasOwnProperty.call(map, key); };
        var named = function (value) { var id = own(legacy, value) ? legacy[value] : value; return own(schemes, id) ? id : null; };
        var read = function (store, key) { try { return window[store].getItem(key); } catch (error) { return null; } };
        var theme = null;
        if (!/${v4LiveOrgPath.source}/.test(path))
          theme = named(new URLSearchParams(location.search).get("theme")) || named(read("sessionStorage", "${v4ThemeStorage.override}"));
        if (!theme) {
          var shared = read("localStorage", "${v4ThemeStorage.shared}");
          var scheme = shared === "light" ? "light" : shared === "system" && matchMedia("(prefers-color-scheme: light)").matches ? "light" : "dark";
          var preferred = {};
          try { preferred = JSON.parse(read("localStorage", "${v4ThemeStorage.preferred}") || "{}") || {}; } catch (error) { preferred = {}; }
          var pick = named(preferred[scheme]);
          theme = pick && schemes[pick] === scheme ? pick : defaults[scheme];
        }
        document.documentElement.setAttribute("data-v4-boot", theme);
      })();`;

const current = readFileSync(indexPath, "utf8");
const from = current.search(/<!-- v4-boot: generated by [^>]*-->/);
const to = current.indexOf(bootEnd);
if (from < 0 || to < from) throw new Error("index.html is missing the v4-boot markers");
const next = `${current.slice(0, from)}${bootStart}
    <style>
${bootGrounds}
    </style>
    <script>
      ${bootScript}
    </script>
    ${current.slice(to)}`;
if (next === current) console.log("index.html v4-boot block is current.");
else if (check) {
  console.error("index.html v4-boot block is stale. Run npm run v4:boot.");
  process.exitCode = 1;
} else {
  writeFileSync(indexPath, next);
  console.log("Updated the index.html v4-boot block.");
}
