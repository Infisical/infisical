const EVENT_TYPE_TO_CLASS = new Map<EventType, AuditLogEventClass>([
  ...AUTHENTICATION_EVENT_TYPES.map((type) => [type, AuditLogEventClass.Authentication] as const),
  ...AUTHORIZATION_EVENT_TYPES.map((type) => [type, AuditLogEventClass.Authorization] as const),
  ...DATA_ACCESS_EVENT_TYPES.map((type) => [type, AuditLogEventClass.DataAccess] as const)
]);

export const MANAGEMENT_EVENT_TYPES: readonly EventType[] = Object.values(EventType).filter(
  (type) => !EVENT_TYPE_TO_CLASS.has(type)
);

export const AUDIT_LOG_EVENT_CLASS_MEMBERS: Record<AuditLogEventClass, readonly EventType[]> = {
  [AuditLogEventClass.Management]: MANAGEMENT_EVENT_TYPES,
  [AuditLogEventClass.Authentication]: AUTHENTICATION_EVENT_TYPES,
  [AuditLogEventClass.Authorization]: AUTHORIZATION_EVENT_TYPES,
  [AuditLogEventClass.DataAccess]: DATA_ACCESS_EVENT_TYPES
};

export const getAuditLogEventClass = (eventType: string): AuditLogEventClass =>
  EVENT_TYPE_TO_CLASS.get(eventType as EventType) ?? AuditLogEventClass.Management;

export const getEventTypesForClasses = (eventClasses: AuditLogEventClass[]): EventType[] =>
  eventClasses.flatMap((eventClass) => AUDIT_LOG_EVENT_CLASS_MEMBERS[eventClass]);
