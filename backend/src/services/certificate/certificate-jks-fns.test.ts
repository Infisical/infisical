type TParsedEntry =
  | { tag: 1; alias: string; protectedKey: Buffer; chain: Buffer[] }
  | { tag: 2; alias: string; certificate: Buffer };

const javaPassword = (password: string) => Buffer.from(password, "utf16le").swap16();
const sha1 = (...parts: Buffer[]) => parts.reduce((h, p) => h.update(p), crypto.createHash("sha1")).digest();

const parseJks = (buf: Buffer, password: string) => {
  let offset = 0;
  const u16 = () => {
    const v = buf.readUInt16BE(offset);
    offset += 2;
    return v;
  };
  const u32 = () => {
    const v = buf.readUInt32BE(offset);
    offset += 4;
    return v;
  };
  const bytes = (n: number) => {
    const v = buf.subarray(offset, offset + n);
    offset += n;
    return v;
  };
  const utf = () => bytes(u16()).toString("utf8");
  const cert = () => {
    expect(utf()).toBe("X.509");
    return bytes(u32());
  };

  expect(u32()).toBe(0xfeedfeed);
  expect(u32()).toBe(2);
  const count = u32();
  const entries: TParsedEntry[] = [];
  for (let i = 0; i < count; i += 1) {
    const tag = u32();
    const alias = utf();
    bytes(8);
    if (tag === 1) {
      const protectedKey = bytes(u32());
      const chainLength = u32();
      const chain = Array.from({ length: chainLength }, cert);
      entries.push({ tag, alias, protectedKey, chain });
    } else {
      expect(tag).toBe(2);
      entries.push({ tag: 2, alias, certificate: cert() });
    }
  }

  const expectedDigest = sha1(javaPassword(password), Buffer.from("Mighty Aphrodite", "utf8"), buf.subarray(0, offset));
  expect(bytes(20).equals(expectedDigest)).toBe(true);
  expect(offset).toBe(buf.length);
  return entries;
};

const recoverPrivateKey = (encryptedPrivateKeyInfo: Buffer, password: string) => {
  const asn1 = forge.asn1.fromDer(forge.util.createBuffer(encryptedPrivateKeyInfo.toString("binary")));
  const [algorithm, encryptedData] = asn1.value as forge.asn1.Asn1[];
  const oid = forge.asn1.derToOid((algorithm.value as forge.asn1.Asn1[])[0].value as string);
  expect(oid).toBe("1.3.6.1.4.1.42.2.17.1.1");

  const protectedKey = Buffer.from(encryptedData.value as string, "binary");
  const salt = protectedKey.subarray(0, 20);
  const encrypted = protectedKey.subarray(20, protectedKey.length - 20);
  const check = protectedKey.subarray(protectedKey.length - 20);
  const passwordBytes = javaPassword(password);

  const plain = Buffer.alloc(encrypted.length);
  let digest = salt;
  for (let i = 0; i < encrypted.length; i += 1) {
    if (i % 20 === 0) digest = sha1(passwordBytes, digest);
    plain[i] = encrypted[i] ^ digest[i % 20];
  }
  expect(sha1(passwordBytes, plain).equals(check)).toBe(true);
  return plain;
};

