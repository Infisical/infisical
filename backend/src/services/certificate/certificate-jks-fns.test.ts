describe("generateJksFromCertificate", () => {
  test("writes one private key entry holding the key, leaf, and chain", () => {
    const jks = generateJksFromCertificate({
      certificate: leaf.certificate,
      certificateChain: `${intermediate.certificate}\n${root.certificate}`,
      privateKey: leaf.privateKey,
      password: PASSWORD,
      alias: "API.Example.com"
    });

    const entry = privateKeyEntry(jks, PASSWORD);
    expect(entry.alias).toBe("api.example.com");
    expect(entry.chain.map((c) => c.toString("base64"))).toEqual(
      [leaf, intermediate, root].map((c) => der(c.certificate).toString("base64"))
    );

    const pkcs8 = crypto.createPrivateKey(leaf.privateKey).export({ type: "pkcs8", format: "der" });
    expect(recoverPrivateKey(entry.protectedKey, PASSWORD).equals(pkcs8)).toBe(true);
  });

  test("does not repeat the leaf when the stored chain already contains it", () => {
    const jks = generateJksFromCertificate({
      certificate: leaf.certificate,
      certificateChain: `${leaf.certificate}\n${intermediate.certificate}`,
      privateKey: leaf.privateKey,
      password: PASSWORD,
      alias: "a"
    });

    expect(privateKeyEntry(jks, PASSWORD).chain).toHaveLength(2);
  });

  test("encodes non-ASCII passwords as Java chars", () => {
    const password = "pässwörd-秘密";
    const jks = generateJksFromCertificate({ ...leaf, password, alias: "a" });
    recoverPrivateKey(privateKeyEntry(jks, password).protectedKey, password);
  });

  test("exports an EC key with its certificate", async () => {
    const keys = (await webcrypto.subtle.generateKey({ name: "ECDSA", namedCurve: "P-256" }, true, [
      "sign",
      "verify"
    ])) as CryptoKeyPair;
    const cert = await x509.X509CertificateGenerator.createSelfSigned({
      serialNumber: "02",
      name: "CN=ec.example.com",
      notBefore: new Date(2026, 0, 1),
      notAfter: new Date(2027, 0, 1),
      signingAlgorithm: { name: "ECDSA", hash: "SHA-256" },
      keys
    });
    const pkcs8 = Buffer.from(await webcrypto.subtle.exportKey("pkcs8", keys.privateKey));

    const jks = generateJksFromCertificate({
      certificate: cert.toString("pem"),
      privateKey: crypto.createPrivateKey({ key: pkcs8, format: "der", type: "pkcs8" }).export({
        type: "pkcs8",
        format: "pem"
      }) as string,
      password: PASSWORD,
      alias: "ec"
    });

    const entry = privateKeyEntry(jks, PASSWORD);
    expectKeyMatchesCertificate(recoverPrivateKey(entry.protectedKey, PASSWORD), entry.chain[0]);
  });

  test("re-encodes an EC key with explicit curve parameters using the named curve", async () => {
    const keys = (await webcrypto.subtle.generateKey({ name: "ECDSA", namedCurve: "P-256" }, true, [
      "sign",
      "verify"
    ])) as CryptoKeyPair;
    const cert = await x509.X509CertificateGenerator.createSelfSigned({
      serialNumber: "03",
      name: "CN=explicit.example.com",
      notBefore: new Date(2026, 0, 1),
      notAfter: new Date(2027, 0, 1),
      signingAlgorithm: { name: "ECDSA", hash: "SHA-256" },
      keys
    });
    const namedPkcs8 = Buffer.from(await webcrypto.subtle.exportKey("pkcs8", keys.privateKey));
    const explicitPkcs8 = toExplicitCurvePkcs8(namedPkcs8);
    const explicitKey = crypto.createPrivateKey({ key: explicitPkcs8, format: "der", type: "pkcs8" });
    expect(explicitKey.export({ type: "pkcs8", format: "der" }).includes(P256_OID_TLV)).toBe(false);

    const jks = generateJksFromCertificate({
      certificate: cert.toString("pem"),
      privateKey: explicitKey.export({ type: "pkcs8", format: "pem" }) as string,
      password: PASSWORD,
      alias: "explicit"
    });

    const entry = privateKeyEntry(jks, PASSWORD);
    const recovered = recoverPrivateKey(entry.protectedKey, PASSWORD);
    expect(recovered.includes(P256_OID_TLV)).toBe(true);
    expectKeyMatchesCertificate(recovered, entry.chain[0]);
  });

  test("rejects EC keys on curves Java does not support", () => {
    const { privateKey } = crypto.generateKeyPairSync("ec", { namedCurve: "secp224r1" });
    expect(() =>
      generateJksFromCertificate({
        certificate: leaf.certificate,
        privateKey: privateKey.export({ type: "pkcs8", format: "pem" }) as string,
        password: PASSWORD,
        alias: "a"
      })
    ).toThrow("P-256, P-384, and P-521 curves only");
  });

  test("rejects a private key that does not belong to the certificate", () => {
    expect(() =>
      generateJksFromCertificate({
        certificate: leaf.certificate,
        privateKey: root.privateKey,
        password: PASSWORD,
        alias: "a"
      })
    ).toThrow("does not match its public key");
  });

  test("rejects key types other than RSA and EC", () => {
    const { privateKey } = crypto.generateKeyPairSync("rsa-pss", { modulusLength: 2048 });
    expect(() =>
      generateJksFromCertificate({
        certificate: leaf.certificate,
        privateKey: privateKey.export({ type: "pkcs8", format: "pem" }) as string,
        password: PASSWORD,
        alias: "a"
      })
    ).toThrow("supports RSA and EC keys only");
  });

  test("requires a non-blank password", () => {
    expect(() => generateJksFromCertificate({ ...leaf, password: "", alias: "a" })).toThrow("Password is required");
    expect(() => generateJksFromCertificate({ ...leaf, password: "   ", alias: "a" })).toThrow("Password is required");
  });

  test("reports an unreadable private key", () => {
    expect(() =>
      generateJksFromCertificate({ certificate: leaf.certificate, privateKey: "nope", password: PASSWORD, alias: "a" })
    ).toThrow("private key could not be read");
  });
});

describe("getJksChainCertificates", () => {
  test("drops the leaf and duplicate certificates", () => {
    expect(
      getJksChainCertificates(
        leaf.certificate,
        `${leaf.certificate}\n${intermediate.certificate}\n${intermediate.certificate}`
      )
    ).toEqual([intermediate.certificate.trim()]);
  });
});

describe("getJksTruststoreCertificates", () => {
  test("keeps the root of an imported chain that has no Infisical CA", () => {
    const trusted = getJksTruststoreCertificates({
      certificate: leaf.certificate,
      fullCertificateChain: `${intermediate.certificate}\n${root.certificate}`
    });
    expect(trusted.map((c) => der(c).toString("base64"))).toEqual(
      [intermediate, root].map((c) => der(c.certificate).toString("base64"))
    );
  });

  test("adds the CA certificate when the stored chain has no root", () => {
    const trusted = getJksTruststoreCertificates({
      certificate: leaf.certificate,
      fullCertificateChain: intermediate.certificate,
      caCertificate: root.certificate
    });
    expect(trusted).toHaveLength(2);
  });

  test("never trusts the leaf and does not repeat the root", () => {
    const trusted = getJksTruststoreCertificates({
      certificate: leaf.certificate,
      fullCertificateChain: `${leaf.certificate}\n${intermediate.certificate}\n${root.certificate}`,
      caCertificate: root.certificate
    });
    expect(trusted).toHaveLength(2);
  });

  test("is empty when there is nothing to trust", () => {
    expect(getJksTruststoreCertificates({ certificate: leaf.certificate, fullCertificateChain: "  \n" })).toEqual([]);
  });
});

describe("generateJksTruststore", () => {
  test("writes each certificate as a trusted entry", () => {
    const jks = generateJksTruststore({
      trustedCertificates: [intermediate.certificate, root.certificate],
      password: PASSWORD,
      alias: "API"
    });

    const entries = parseJks(jks, PASSWORD);
    expect(entries.map((e) => [e.tag, e.alias])).toEqual([
      [2, "api-ca-1"],
      [2, "api-ca-2"]
    ]);
    const [first] = entries;
    if (first.tag !== 2) throw new Error("expected a trusted certificate entry");
    expect(first.certificate.equals(der(intermediate.certificate))).toBe(true);
  });
});
