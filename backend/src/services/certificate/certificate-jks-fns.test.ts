const issue = (commonName: string, issuer?: { cert: forge.pki.Certificate; key: forge.pki.rsa.PrivateKey }) => {
  const keys = forge.pki.rsa.generateKeyPair(2048);
  const cert = forge.pki.createCertificate();
  cert.publicKey = keys.publicKey;
  cert.serialNumber = "01";
  cert.validity.notBefore = new Date(2026, 0, 1);
  cert.validity.notAfter = new Date(2027, 0, 1);
  cert.setSubject([{ name: "commonName", value: commonName }]);
  cert.setIssuer(issuer ? issuer.cert.subject.attributes : [{ name: "commonName", value: commonName }]);
  cert.sign(issuer?.key ?? keys.privateKey, forge.md.sha256.create());
  return {
    cert,
    key: keys.privateKey,
    certificate: forge.pki.certificateToPem(cert),
    privateKey: forge.pki.privateKeyInfoToPem(forge.pki.wrapRsaPrivateKey(forge.pki.privateKeyToAsn1(keys.privateKey)))
  };
};

